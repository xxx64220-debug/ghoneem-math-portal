function canonicalMathLesson(track, value) {
  if (!MATH_LESSONS[track]) return String(value || '').trim();
  const name = MATH_LESSON_ALIASES[String(value || '').trim().toLowerCase()];
  if (!name || !MATH_LESSONS[track].includes(name)) throw new Error('Choose a lesson from the lesson list for this track. Mixed import categories must be classified per question.');
  return name;
}
function questionLessonMarkup(track, value) {
  if (!MATH_LESSONS[track]) return field('qtopic','Lesson',value);
  let selected = ''; try { selected = canonicalMathLesson(track,value); } catch (_) {}
  return select('qtopic','Lesson',[['','Choose a lesson'],...MATH_LESSONS[track].map(n=>[n,n])],selected);
}
function normalizeQuestionLesson(track, question) {
  const lesson = canonicalMathLesson(track,question.topic);
  if (!MATH_LESSONS[track]) return question;
  return {...question, topic:lesson, assets:{...(question.assets || {}), curriculum_lesson:lesson,
    ...(question.topic !== lesson ? {lesson_subtopic:question.assets?.lesson_subtopic || question.topic} : {})}};
}
